#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd -- "${SCRIPT_DIR}/.." && pwd)"
cd "${ROOT_DIR}"

python_bin="${PYTHON_BIN:-python}"
pretrained_checkpoint="${PRETRAINED_CHECKPOINT:-/path/to/checkpoint}"
benchmark="${BENCHMARK:-MT50}"
cuda_visible_devices="${CUDA_VISIBLE_DEVICES:-7}"
mujoco_gl="${MUJOCO_GL:-egl}"
output_dir="${OUTPUT_DIR:-${ROOT_DIR}/experiments/metaworld}"
unnorm_key="${UNNORM_KEY:-}"
num_trials_per_task="${NUM_TRIALS_PER_TASK:-10}"
max_envs="${MAX_ENVS:-0}"
max_episode_steps="${MAX_EPISODE_STEPS:-0}"
save_video="${SAVE_VIDEO:-y}"
save_action="${SAVE_ACTION:-n}"
save_debug_frame="${SAVE_DEBUG_FRAME:-y}"
center_crop="${CENTER_CROP:-True}"
render_width="${RENDER_WIDTH:-480}"
render_height="${RENDER_HEIGHT:-480}"
image_resize="${IMAGE_RESIZE:-224}"
include_fallback_only_envs="${INCLUDE_FALLBACK_ONLY_ENVS:-n}"
skip_unsupported_envs="${SKIP_UNSUPPORTED_ENVS:-y}"
num_images_in_input="${NUM_IMAGES_IN_INPUT:-1}"
use_proprio="${USE_PROPRIO:-False}"
use_l1_regression="${USE_L1_REGRESSION:-True}"
use_film="${USE_FILM:-False}"
use_minivlm="${USE_MINIVLM:-True}"
use_pro_version="${USE_PRO_VERSION:-True}"
use_gate="${USE_GATE:-True}"
use_latent_outputs="${USE_LATENT_OUTPUTS:-True}"
camera_name="${CAMERA_NAME:-corner2}"
image_flip="${IMAGE_FLIP:-both}"
apply_lerobot_camera_patch="${APPLY_LEROBOT_CAMERA_PATCH:-y}"
lerobot_camera_id="${LEROBOT_CAMERA_ID:-2}"
lerobot_camera_pos="${LEROBOT_CAMERA_POS:-0.75,0.075,0.7}"

cmd=(
  "${python_bin}" experiments/robot/metaworld/run_metaworld_eval.py
  --pretrained_checkpoint "${pretrained_checkpoint}"
  --benchmark "${benchmark}"
  --mujoco_gl "${mujoco_gl}"
  --output_dir "${output_dir}"
  --num_trials_per_task "${num_trials_per_task}"
  --max_envs "${max_envs}"
  --max_episode_steps "${max_episode_steps}"
  --include_fallback_only_envs "${include_fallback_only_envs}"
  --skip_unsupported_envs "${skip_unsupported_envs}"
  --center_crop "${center_crop}"
  --render_width "${render_width}"
  --render_height "${render_height}"
  --image_resize "${image_resize}"
  --camera_name "${camera_name}"
  --image_flip "${image_flip}"
  --apply_lerobot_camera_patch "${apply_lerobot_camera_patch}"
  --lerobot_camera_id "${lerobot_camera_id}"
  --lerobot_camera_pos "${lerobot_camera_pos}"
  --num_images_in_input "${num_images_in_input}"
  --use_proprio "${use_proprio}"
  --use_l1_regression "${use_l1_regression}"
  --use_film "${use_film}"
  --use_minivlm "${use_minivlm}"
  --use_pro_version "${use_pro_version}"
  --use_gate "${use_gate}"
  --use_latent_outputs "${use_latent_outputs}"
  --save_video "${save_video}"
  --save_action "${save_action}"
  --save_debug_frame "${save_debug_frame}"

)

if [[ -n "${unnorm_key}" ]]; then
  cmd+=(--unnorm_key "${unnorm_key}")
fi

TOKENIZERS_PARALLELISM="${TOKENIZERS_PARALLELISM:-false}" CUDA_VISIBLE_DEVICES="${cuda_visible_devices}" "${cmd[@]}" "$@"
